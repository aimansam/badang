// Multi-byte XOR obfuscation for all sensitive binary data.
//
// ## Adding new encrypted constants
//
// 1. Choose the plaintext value (string, byte array, etc.)
// 2. XOR each byte with the key (cycling through key bytes):
//    ```python
//    K=[0xd3,0x7a,0x91,0xe5,0x2f,0xb8,0x64,0x1c]
//    encrypted = [b^K[i%len(K)] for i,b in enumerate(plaintext_bytes)]
//    ```
// 3. Add as a `pub const` in this file
// 4. Use `s()` for strings, `b()` for byte vectors, `ba()` for fixed arrays,
//    `byte()` for single bytes

const K: &[u8] = &[0xD3, 0x7A, 0x91, 0xE5, 0x2F, 0xB8, 0x64, 0x1C];

pub fn s(enc: &[u8]) -> String {
    enc.iter().enumerate().map(|(i, &b)| (b ^ K[i % K.len()]) as char).collect()
}

pub fn b(enc: &[u8]) -> Vec<u8> {
    enc.iter().enumerate().map(|(i, &b)| b ^ K[i % K.len()]).collect()
}

pub fn ba<const N: usize>(enc: &[u8; N]) -> [u8; N] {
    let mut out = [0u8; N];
    for i in 0..N {
        out[i] = enc[i] ^ K[i % K.len()];
    }
    out
}

pub fn byte(enc: u8) -> u8 {
    enc ^ K[0]
}

